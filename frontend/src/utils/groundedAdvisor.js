import { formatINR } from './formatters';

export function getGroundedAdvisorResponse(query, context) {
  const q = query.toLowerCase();
  const price = context.predicted_price || 0;
  const rate = context.rate_per_sqft || 0;
  const fin = context.finance || {};
  const city = context.city || 'your city';
  const locality = context.locality || 'this micro-market';
  const bhk = context.bhk || 3;

  const dp = fin.down_payment || 0;
  const loan = fin.loan_amount || 0;
  const emi = fin.monthly_emi || 0;
  const stamp = fin.stamp_duty || 0;
  const gst = fin.gst || 0;
  const total = fin.total_acquisition_cost || (price + stamp + gst);
  const upfrontCash = dp + stamp + gst;
  const ltvPct = Math.round((fin.ltv_ratio || 0.75) * 100);

  // 1. Upfront out-of-pocket cash query
  if (q.includes('out-of-pocket') || q.includes('upfront') || q.includes('cash needed') || q.includes('down payment')) {
    return `Here is your exact out-of-pocket cash breakdown for this ${bhk} BHK in ${locality}, ${city}:

• Down Payment (Equity): ${formatINR(dp)} (${Math.round((dp / price) * 100)}% of property value)
• Stamp Duty & Registration: ${formatINR(stamp)} (State statutory fee)
• GST on Property: ${gst === 0 ? '₹0 (Exempt — Ready to Move)' : formatINR(gst)}
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
Total Immediate Cash Needed: ${formatINR(upfrontCash)}

The remaining ${formatINR(loan)} is covered by your sanctioned home loan. You will need ${formatINR(upfrontCash)} available in liquid funds before registry and possession.`;
  }

  // 2. EMI Calculation query
  if (q.includes('emi') || q.includes('monthly') || q.includes('interest rate') || q.includes('tenure')) {
    return `Your estimated monthly EMI is ${formatINR(emi)}.

Here is how this is structured based on RBI standards:
• Financed Principal: ${formatINR(loan)}
• Monthly Outflow: ${formatINR(emi)} / month
• Annual Debt Service: ${formatINR(emi * 12)} / year

This is computed using standard reducing-balance amortization (P × r × (1+r)ⁿ / ((1+r)ⁿ - 1)). If you wish to reduce your monthly EMI, you can increase your loan tenure or increase your upfront down payment.`;
  }

  // 3. Stamp duty and taxes query
  if (q.includes('stamp') || q.includes('duty') || q.includes('registration') || q.includes('tax')) {
    return `For ${city}, statutory government charges on this property total ${formatINR(stamp + gst)}:

• State Stamp Duty & Registration: ${formatINR(stamp)} (based on state schedule for ${city})
• GST: ${gst === 0 ? '₹0 (Nil GST for completed / ready-to-move properties with completion certificate)' : `${formatINR(gst)} (Under-construction rate)`}
• Base Valuation: ${formatINR(price)}
• Total Statutory Overhead: ${Math.round(((stamp + gst) / price) * 100)}% of property price

Stamp duty must be paid via official e-stamping before deed execution.`;
  }

  // 4. RBI LTV Cap query
  if (q.includes('ltv') || q.includes('rbi') || q.includes('loan limit') || q.includes('eligible loan')) {
    let tierText = 'Above ₹75 Lakhs → 75% max LTV';
    if (loan <= 3000000) tierText = 'Up to ₹30 Lakhs → 90% max LTV';
    else if (loan <= 7500000) tierText = '₹30L to ₹75 Lakhs → 80% max LTV';

    return `Under the RBI Master Direction on Housing Finance, your maximum Loan-to-Value (LTV) cap is ${ltvPct}%.

• Bracket: ${tierText}
• Estimated Property Value: ${formatINR(price)}
• Sanctioned Principal Cap: ${formatINR(loan)}
• Mandatory Minimum Equity: ${formatINR(dp)}

Banks are legally prohibited from funding stamp duty or registration fees as part of the home loan principal.`;
  }

  // 5. Fair price / value per sqft query
  if (q.includes('fair') || q.includes('sqft') || q.includes('sq.ft') || q.includes('rate') || q.includes('worth') || q.includes('price')) {
    return `Valuation Assessment for ${locality}, ${city}:

• Fair Market Estimate: ${formatINR(price)}
• Unit Rate: ₹${Math.round(rate).toLocaleString('en-IN')} / sq.ft
• Configuration: ${bhk} BHK apartment
• Total Acquisition: ${formatINR(total)} (including all closing costs)

This valuation is generated by our calibrated Random Forest model using verified spatial micro-market transactions in ${city}.`;
  }

  // 6. Greetings / General inquiry
  if (q.includes('hi') || q.includes('hello') || q.includes('hey') || q.includes('help')) {
    return `Hello! I am your GrihaValue AI advisor for this ${bhk} BHK property in ${locality}, ${city} (estimated at ${formatINR(price)}).

Here are quick insights I can provide:
1. Total out-of-pocket cash required: ${formatINR(upfrontCash)}
2. Estimated monthly EMI: ${formatINR(emi)}
3. Stamp duty & registration for ${city}: ${formatINR(stamp)}
4. Maximum RBI loan eligibility: ${formatINR(loan)} (${ltvPct}% LTV)

What specific financial breakdown would you like to explore?`;
  }

  // Default intelligent grounded fallback
  return `Based on the valuation model for this ${bhk} BHK in ${locality}, ${city}:

• Estimated Market Value: ${formatINR(price)} (₹${Math.round(rate).toLocaleString('en-IN')}/sq.ft)
• Bank Loan Principal: ${formatINR(loan)} (@ ${ltvPct}% LTV)
• Monthly EMI: ${formatINR(emi)}
• Upfront Closing Cash (Down Payment + Taxes): ${formatINR(upfrontCash)}
• Total Acquisition Cost: ${formatINR(total)}

Feel free to ask about reducing your EMI, stamp duty rates in ${city}, or RBI loan eligibility rules!`;
}
